// Generates src/legacy-releases.mjs: SHA-384 digests of the served files of releases that
// predate release manifests and still get traffic. Each npm tarball is checked against the
// registry's sha512 integrity first. Run: node tools/legacy-releases.mjs
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

// Versions without a release manifest that rum.hlx.page logs showed traffic for (Nov 2026),
// including what the ^1 and ^2 aliases point to. Add a version here, rerun, and review the diff.
export const VERSIONS = {
  '@adobe/helix-rum-js': ['1.9.0', '2.10.5', '2.14.0', '2.15.0', '2.17.0'],
  '@adobe/helix-rum-enhancer': ['1.23.1', '2.34.2', '2.45.1', '2.47.3', '2.51.0', '2.51.1', '2.52.0'],
};

function walk(root, dir) {
  return readdirSync(join(root, dir), { withFileTypes: true }).flatMap((entry) => {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) {
      return walk(root, path);
    }
    return entry.isFile() && entry.name.endsWith('.js') && !entry.name.endsWith('.map.js') ? [path] : [];
  });
}

async function digests(name, version) {
  const doc = await (await fetch(`https://registry.npmjs.org/${name.replace('/', '%2f')}/${version}`)).json();
  const bytes = Buffer.from(await (await fetch(doc.dist.tarball)).arrayBuffer());
  const integrity = `sha512-${createHash('sha512').update(bytes).digest('base64')}`;
  if (integrity !== doc.dist.integrity) {
    throw new Error(`${name}@${version}: tarball does not match registry integrity`);
  }
  const dir = mkdtempSync(join(tmpdir(), 'legacy-release-'));
  try {
    writeFileSync(join(dir, 'p.tgz'), bytes);
    execFileSync('tar', ['-xzf', join(dir, 'p.tgz'), '-C', dir]);
    const root = join(dir, 'package');
    const files = ['src', 'dist']
      .filter((d) => readdirSync(root).includes(d))
      .flatMap((d) => walk(root, d))
      .sort();
    return Object.fromEntries(files.map((path) => {
      const content = readFileSync(join(root, path));
      return [path, {
        integrity: `sha384-${createHash('sha384').update(content).digest('base64')}`,
        size: content.length,
      }];
    }));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const table = {};
for (const [name, versions] of Object.entries(VERSIONS)) {
  table[name] = {};
  for (const version of versions) {
    // eslint-disable-next-line no-await-in-loop
    table[name][version] = await digests(name, version);
  }
}
